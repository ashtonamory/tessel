//! HTML/CSS twins of layout fixtures (§11): the same document written as
//! absolutely positioned boxes and flexbox, so a browser can lay it out and
//! the page can compare the browser's boxes with the expected geometry.
//!
//! Inputs map one to one (the §3.5 table): stored `x`/`y`/`width`/`height`,
//! sizing, gaps, padding, alignment, min/max. The one exception is groups,
//! which CSS has no box for: a group is written as a box of its computed
//! size with its children at their computed offsets inside it, so only the
//! group's own placement in the flow is checked by the browser.

use std::fmt::Write as _;

use doc::{
    Align, Direction, Document, Justify, LineHeight, Node, NodeKind, Sizing, TextAlign, TextSizing,
};

use crate::flex::{effective_sizing, in_flow, resolve_gaps, resolve_space, text_wraps};
use crate::geometry::Geometry;
use crate::text::{effective_text_style, resolve_family};

/// Expected box of a node in page coordinates: `[x, y, width, height]`.
pub type ExpectedBox = [f64; 4];

/// The HTML page for one fixture. `geometry` is only used for groups (see
/// the module docs); `expected` is what the page checks the browser
/// against.
pub fn fixture_html(
    name: &str,
    description: &str,
    doc: &Document,
    geometry: &Geometry,
    expected: &[(String, ExpectedBox)],
) -> String {
    let mut body = String::new();
    for page in doc.pages.iter().take(1) {
        for n in &page.children {
            let parent = Parent {
                origin: (0.0, 0.0),
                flex: None,
                group: false,
            };
            node_html(doc, geometry, n, parent, &mut body, 1);
        }
    }
    let expected_js: Vec<String> = expected
        .iter()
        .map(|(id, b)| format!("[{:?}, [{}, {}, {}, {}]]", id, b[0], b[1], b[2], b[3]))
        .collect();
    format!(
        r#"<!doctype html>
<!-- Generated by scripts/layout-parity.sh from crates/layout/tests/fixtures/{name}.json; do not edit. -->
<html>
<head>
<meta charset="utf-8">
<title>layout parity: {name}</title>
<style>
* {{ box-sizing: border-box; margin: 0; padding: 0; }}
body {{ font-family: sans-serif; }}
#page {{ position: absolute; left: 0; top: 0; width: 10000px; height: 10000px; }}
#page div {{ outline: 1px solid rgba(37, 99, 235, 0.35); background: rgba(37, 99, 235, 0.04); }}
#report {{ position: fixed; right: 0; top: 0; max-width: 46em; background: #fff; border: 1px solid #888;
  font: 12px/1.4 monospace; padding: 8px; z-index: 1; }}
#report .fail {{ color: #b91c1c; }} #report .pass {{ color: #15803d; }}
</style>
</head>
<body>
<div id="page">
{body}</div>
<div id="report"><b>{name}</b>: {description}<table id="rows"></table></div>
<script>
const EXPECTED = [{expected}];
const TOLERANCE = 0.5;
const page = document.getElementById("page").getBoundingClientRect();
let failures = 0;
const rows = document.getElementById("rows");
for (const [id, want] of EXPECTED) {{
  const el = document.querySelector(`[data-id="${{id}}"]`);
  const r = el ? el.getBoundingClientRect() : null;
  const got = r ? [r.left - page.left, r.top - page.top, r.width, r.height] : null;
  const ok = got && got.every((v, i) => Math.abs(v - want[i]) <= TOLERANCE);
  const text = el && el.dataset.kind === "text";
  if (!ok) failures++;
  const fmt = (b) => b ? b.map((v) => +v.toFixed(2)).join(", ") : "missing";
  rows.insertAdjacentHTML("beforeend", `<tr class="${{ok ? "pass" : "fail"}}"><td>${{ok ? "PASS" : "FAIL"}}</td>` +
    `<td>${{id}}${{text ? " (text: font metrics may differ)" : ""}}</td><td>want ${{fmt(want)}}</td><td>got ${{fmt(got)}}</td></tr>`);
}}
window.parityResult = {{ name: {name:?}, failures, total: EXPECTED.length }};
document.title = (failures ? "FAIL " : "PASS ") + {name:?};
</script>
</body>
</html>
"#,
        expected = expected_js.join(", "),
        description = escape(description),
    )
}

/// The index page: every fixture in an iframe and a summary.
pub fn index_html(names: &[String]) -> String {
    let frames: String = names
        .iter()
        .map(|n| {
            format!(
                "<section><h2><a href=\"{n}.html\">{n}</a></h2><iframe src=\"{n}.html\" data-name=\"{n}\"></iframe></section>\n"
            )
        })
        .collect();
    format!(
        r#"<!doctype html>
<!-- Generated by scripts/layout-parity.sh; do not edit. -->
<html>
<head>
<meta charset="utf-8">
<title>layout parity</title>
<style>
body {{ font: 14px sans-serif; margin: 16px; }}
iframe {{ width: 100%; height: 420px; border: 1px solid #ccc; }}
#summary {{ font: bold 16px monospace; }}
</style>
</head>
<body>
<h1>Layout fixtures vs. this browser</h1>
<p id="summary">running…</p>
{frames}<script>
window.addEventListener("load", () => {{
  const results = [...document.querySelectorAll("iframe")].map((f) => f.contentWindow.parityResult);
  const failed = results.filter((r) => !r || r.failures > 0);
  window.parityResults = results;
  document.getElementById("summary").textContent = failed.length
    ? `FAIL: ${{failed.map((r) => r ? r.name : "?").join(", ")}}`
    : `PASS: all ${{results.length}} fixtures match`;
}});
</script>
</body>
</html>
"#
    )
}

/// Where a node's children are written.
#[derive(Clone, Copy)]
struct Parent<'a> {
    /// The parent box's page origin.
    origin: (f64, f64),
    /// The parent's auto-layout, which places its flow children.
    flex: Option<&'a doc::AutoLayout>,
    /// The parent is a group: children sit at their computed offsets.
    group: bool,
}

fn escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn px(v: f32) -> String {
    format!("{}px", (v as f64 * 100.0).round() / 100.0)
}

fn align(a: Align) -> &'static str {
    match a {
        Align::Start => "flex-start",
        Align::Center => "center",
        Align::End => "flex-end",
        Align::Stretch => "stretch",
        Align::Baseline => "baseline",
    }
}

fn node_html(
    doc: &Document,
    geometry: &Geometry,
    node: &Node,
    parent: Parent,
    out: &mut String,
    depth: usize,
) {
    let mut css: Vec<String> = Vec::new();
    let flex_parent = parent.flex.filter(|_| in_flow(node));
    if !node.visible {
        css.push("display: none".into());
    }
    let (sw, sh) = effective_sizing(node, flex_parent.is_some());
    let group_box = match &node.kind {
        NodeKind::Group(_) => geometry.get(&node.id).map(|g| g.bounds),
        _ => None,
    };

    // Position.
    if flex_parent.is_some() {
        css.push("position: relative".into());
    } else {
        let (left, top) = match geometry.get(&node.id) {
            Some(g) if parent.group || group_box.is_some() => {
                (g.bounds.x0 - parent.origin.0, g.bounds.y0 - parent.origin.1)
            }
            _ => (node.x as f64, node.y as f64),
        };
        css.push("position: absolute".into());
        css.push(format!("left: {}px", round2(left)));
        css.push(format!("top: {}px", round2(top)));
    }

    // Size.
    match group_box {
        Some(b) => {
            css.push(format!("width: {}px", round2(b.width())));
            css.push(format!("height: {}px", round2(b.height())));
        }
        None => {
            if sw == Sizing::Fixed {
                css.push(format!("width: {}", px(node.width.max(0.0))));
            }
            if sh == Sizing::Fixed {
                css.push(format!("height: {}", px(node.height.max(0.0))));
            }
        }
    }

    // As a flex item.
    if let Some(al) = flex_parent {
        let (main, cross) = match al.direction {
            Direction::Row => (sw, sh),
            Direction::Column => (sh, sw),
        };
        css.push(if main == Sizing::Fill {
            "flex: 1 1 0px".into()
        } else {
            "flex: 0 0 auto".into()
        });
        if cross == Sizing::Fill {
            css.push("align-self: stretch".into());
        } else if let Some(a) = node.layout_child.align_self {
            css.push(format!("align-self: {}", align(a)));
        }
        let lc = &node.layout_child;
        for (prop, v) in [
            ("min-width", lc.min_width),
            ("max-width", lc.max_width),
            ("min-height", lc.min_height),
            ("max-height", lc.max_height),
        ] {
            if let Some(v) = v {
                css.push(format!("{prop}: {}", px(v.max(0.0))));
            }
        }
    }

    if node.rotation != 0.0 {
        css.push(format!("transform: rotate({}deg)", node.rotation));
    }

    // As a flex container.
    let own = match &node.kind {
        NodeKind::Frame(f) => f.layout.as_ref(),
        _ => None,
    };
    if let Some(al) = own {
        let (gap, cross_gap) = resolve_gaps(doc, al);
        let (column_gap, row_gap) = match al.direction {
            Direction::Row => (gap, cross_gap),
            Direction::Column => (cross_gap, gap),
        };
        css.push("display: flex".into());
        css.push(
            match al.direction {
                Direction::Row => "flex-direction: row",
                Direction::Column => "flex-direction: column",
            }
            .into(),
        );
        if al.wrap {
            css.push("flex-wrap: wrap".into());
        }
        css.push(format!("column-gap: {}", px(column_gap)));
        css.push(format!("row-gap: {}", px(row_gap)));
        let p: Vec<String> = al
            .padding
            .iter()
            .map(|s| px(resolve_space(doc, s)))
            .collect();
        css.push(format!("padding: {}", p.join(" ")));
        css.push(format!(
            "justify-content: {}",
            match al.justify {
                Justify::Start => "flex-start",
                Justify::Center => "center",
                Justify::End => "flex-end",
                Justify::SpaceBetween => "space-between",
            }
        ));
        css.push(format!("align-items: {}", align(al.align)));
        css.push("align-content: flex-start".into());
    }

    // Text.
    let mut content = String::new();
    if let NodeKind::Text(t) = &node.kind {
        let style = effective_text_style(doc, node).expect("text node");
        let wraps = if flex_parent.is_some() {
            text_wraps(node)
        } else {
            t.sizing != TextSizing::AutoWidth
        };
        css.push(format!(
            "white-space: {}",
            if wraps { "pre-wrap" } else { "pre" }
        ));
        css.push(format!(
            "font-family: '{}', sans-serif",
            resolve_family(doc, style).replace('\'', "")
        ));
        css.push(format!("font-size: {}", px(style.font_size)));
        css.push(format!("font-weight: {}", style.font_weight));
        if style.italic {
            css.push("font-style: italic".into());
        }
        css.push(format!(
            "line-height: {}",
            match style.line_height {
                LineHeight::Auto => "normal".to_string(),
                LineHeight::Px(v) => px(v),
                LineHeight::Percent(p) => format!("{p}%"),
            }
        ));
        if style.letter_spacing != 0.0 {
            css.push(format!("letter-spacing: {}", px(style.letter_spacing)));
        }
        css.push(format!(
            "text-align: {}",
            match t.align {
                TextAlign::Left => "left",
                TextAlign::Center => "center",
                TextAlign::Right => "right",
                TextAlign::Justify => "justify",
            }
        ));
        content = escape(&t.content);
    }

    let indent = "  ".repeat(depth);
    let _ = write!(
        out,
        "{indent}<div data-id=\"{}\" data-kind=\"{}\" title=\"{}\" style=\"{}\">{content}",
        escape(&node.id.to_string()),
        node.kind.tag(),
        escape(&node.name),
        escape(&css.join("; ")),
    );
    if let Some(children) = node.children() {
        out.push('\n');
        let origin = match (group_box, geometry.get(&node.id)) {
            (Some(b), _) => (b.x0, b.y0),
            (None, Some(g)) => (g.origin().x, g.origin().y),
            (None, None) => (0.0, 0.0),
        };
        let child_parent = Parent {
            origin,
            flex: own,
            group: group_box.is_some(),
        };
        for c in children {
            node_html(doc, geometry, c, child_parent, out, depth + 1);
        }
        out.push_str(&indent);
    }
    out.push_str("</div>\n");
}

fn round2(v: f64) -> f64 {
    (v * 100.0).round() / 100.0
}
